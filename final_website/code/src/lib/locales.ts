export function labels(locale: LocaleKey) {
  const [language, latest, learn, watch, search, missing, original] = core[locale];
  const values = extra[locale].split('|');
  if (values.length !== extraKeys.length || [...values, ...core[locale]].some(value => !value.trim())) throw new Error(`Incomplete interface for ${locale}`);
  const fields = Object.fromEntries(extraKeys.map((key, index) => [key, values[index]])) as Record<typeof extraKeys[number], string>;
  return { ...fields, language, latest, learn, watch, search, missing, original };
}
